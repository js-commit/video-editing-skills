#!/usr/bin/env python3
"""Render a compare_cutlists.py --record results.jsonl as a markdown scoreboard.

Each row is one video: the autonomous aroll-draft cut scored against a
hand-made cut of the same source. Later rows for the same label supersede
earlier ones, so re-running a video updates its row in place.

Usage: results_table.py results.jsonl [-o RESULTS.md]
"""
import argparse
import json
import os


def load(path):
    rows = {}
    order = []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r["label"] not in rows:
                order.append(r["label"])
            rows[r["label"]] = r  # last write wins
    return [rows[k] for k in order]


def mmss(sec):
    return f"{int(sec) // 60}:{int(sec) % 60:02d}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("jsonl", help="the results.jsonl compare_cutlists.py --record appends to")
    ap.add_argument("-o", "--out", help="write markdown here (default: stdout)")
    args = ap.parse_args()

    rows = load(args.jsonl)
    if not rows:
        raise SystemExit("no results recorded yet")

    out = []
    out.append("# aroll-draft vs. hand-edited cuts — scoreboard\n")
    out.append("Autonomous cut scored against a hand-made cut of the same source. "
               "`agree` is the share of the manual cut's kept content the skill also kept. "
               "**bleed** = fragments of removed words left audible; **clip** = kept words chopped "
               "at a boundary. Lower is better, and only the skill's columns are under test.\n")
    out.append("| video | length | agree | skill bleed/clip | manual bleed/clip | skill kept | manual kept |")
    out.append("|---|---:|---:|---:|---:|---:|---:|")
    for r in rows:
        out.append(
            f"| {r['label']} | {mmss(r['media_seconds'])} | {r['agreement_pct_of_benchmark']:.1f} % "
            f"| **{r['cand_bleeds']} / {r['cand_clipped']}** | {r['bench_bleeds']} / {r['bench_clipped']} "
            f"| {mmss(r['cand_kept_s'])} | {mmss(r['bench_kept_s'])} |"
        )

    n = len(rows)
    agree = sum(r["agreement_pct_of_benchmark"] for r in rows) / n
    cb = sum(r["cand_bleeds"] for r in rows)
    cc = sum(r["cand_clipped"] for r in rows)
    bb = sum(r["bench_bleeds"] for r in rows)
    bc = sum(r["bench_clipped"] for r in rows)
    clean = sum(1 for r in rows if r["cand_bleeds"] == 0 and r["cand_clipped"] == 0)
    out.append(f"\n**{n} video{'s' if n != 1 else ''}** · mean agreement **{agree:.1f} %** · "
               f"skill totals **{cb} bleeds / {cc} clipped** vs. manual {bb} / {bc} · "
               f"**{clean}/{n}** artifact-free.\n")
    out.append("Generated by `results_table.py` from `results.jsonl`.")

    text = "\n".join(out) + "\n"
    if args.out:
        with open(args.out, "w") as fh:
            fh.write(text)
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
